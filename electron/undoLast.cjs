/**
 * Слепой Backspace нельзя считать безопасным: одинаковое имя процесса или
 * заголовок окна не подтверждают поле, документ, выделение или позицию курсора.
 * До реализации проверки состояния цели команда только объясняет отказ.
 */
function planUndo({ text = '' } = {}) {
  if (!String(text || '').trim()) return { ok: false, reason: 'нечего убирать' };
  return { ok: false, reason: 'неподтверждённая позиция курсора' };
}

module.exports = { planUndo };
