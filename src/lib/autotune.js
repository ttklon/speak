/**
 * Значения, которые приложение выбирает за человека.
 *
 * Диктовка — это «нажал и говоришь», а не «сначала настрой семь тумблеров».
 * Каждый пункт ниже раньше был отдельной настройкой; на практике у всех должен
 * стоять именно этот вариант, а неправильный выбор человека делал приложение
 * медленнее или тише. Поэтому значения задаются здесь, а не в интерфейсе:
 * экран настроек показывает только то, что действительно зависит от вкуса.
 *
 * Модуль намеренно чистый (без window/electron): его проверяют тесты и
 * `npm run check:settings`.
 */

export const TUNED = Object.freeze({
  // Постобработка текста — смысл диктовки: без неё в поле уходит «э-э ну привет».
  aiProcessing: true,
  // Ждать полировку дольше 0,9 с нельзя — вставка перестаёт быть мгновенной.
  // Включается она тумблером (по умолчанию — вкл., см. config.js), потому что
  // это вкус: кому-то нужны строгие формулировки, кому-то дословная речь.
  aiPolishBudgetMs: 900,
  // VAD отсекает тишину и паузы: ответ раньше, выдуманных фраз меньше.
  vadEnabled: true,
  // Медленная фраза сама переключает на быструю модель и говорит об этом.
  autoOptimize: true,
  // Вставка через буфер: работает везде и не зависит от раскладки.
  insertMethod: 'clipboard',
  // История буфера и диктовок: 2000 записей на месяц плюс бюджет по весу
  // (см. lib/clipboardBudget.js) — «сколько хранить» больше не вопрос.
  clipboardMaxItems: 2000,
  clipboardRetentionDays: 30,
  dictationRetentionDays: 30,
  // Пароли в истории буфера всегда маскируются, уведомления всегда включены.
  hidePasswords: true,
  notifications: true,
  // Обновления: тихая проверка раз в сутки, стабильный канал.
  checkUpdates: true,
  updateChannel: 'stable',
  // Эффект печати убран: он задерживал появление готового текста.
  typingEffect: false,
  // Перевод инструкций — на английский, как в подписи самой инструкции.
  translateTarget: 'en',
});

/**
 * Привести настройки к «идеальным»: подменить только те ключи, которые
 * выбирает приложение. Если менять нечего — возвращается тот же объект, чтобы
 * React не перерисовывал дерево зря.
 *
 * @param {object} settings сохранённые настройки
 * @returns {object} те же или исправленные настройки
 */
export function tuneSettings(settings) {
  if (!settings || typeof settings !== 'object') return { ...TUNED };
  let next = null;
  for (const [key, value] of Object.entries(TUNED)) {
    if (settings[key] !== value) {
      if (!next) next = { ...settings };
      next[key] = value;
    }
  }
  return next || settings;
}

/**
 * Какие ключи приложение задаёт само — для проверки настроек и документации.
 */
export const TUNED_KEYS = Object.freeze(Object.keys(TUNED));

export default { TUNED, TUNED_KEYS, tuneSettings };
