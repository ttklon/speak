import { describe, expect, it } from 'vitest';
import { correctionSpan, dropSelfCorrections, dropStutter } from './selfCorrect.js';

const fix = (text) => dropSelfCorrections(text);

describe('оговорки: отменённое не остаётся в тексте', () => {
  it('не схлопывает соседние абзацы, отступы и двойные пробелы в коде', () => {
    const source = 'Заметка:\n\nВстреча в четыре, то есть в три часа.\n\n  код  здесь';
    expect(fix(source)).toEqual({ text: 'Заметка:\n\nВстреча в три часа.\n\n  код  здесь', fixes: 1 });
    expect(fix('Заголовок\n  в четыре, то есть в три часа.').text).toBe('Заголовок\n  в три часа.');
    expect(fix('код  здесь: встреча в четыре, то есть в три часа.').text).toBe('код  здесь: встреча в три часа.');
  });

  it('не ищет замену на другой строке', () => {
    const source = 'Встреча в четыре, то есть\nв три часа.';
    expect(fix(source)).toEqual({ text: source, fixes: 0 });
  });

  it('находит отдельный маркер после похожей подстроки', () => {
    expect(fix('ТочнееX встреча в четыре, точнее в три часа.')).toEqual({
      text: 'ТочнееX встреча в три часа.', fixes: 1,
    });
  });
  it('«в четыре… то есть в три» → остаётся три', () => {
    const res = fix('Встреча в четыре, то есть в три часа.');
    expect(res.text).toBe('Встреча в три часа.');
    expect(res.fixes).toBe(1);
  });

  it('многоточие вместо запятой — тоже поправка', () => {
    expect(fix('Звонок в 4… то есть в 3 часа.').text).toBe('Звонок в 3 часа.');
  });

  it('«нет» между вариантами: остаётся второй', () => {
    expect(fix('Созвонимся в три, нет, в четыре часа.').text).toBe('Созвонимся в четыре часа.');
  });

  it('«ой» перед другим именем: остаётся верное имя', () => {
    expect(fix('Позвони Пете, ой, Васе.').text).toBe('Позвони Васе.');
  });

  it('«простите» и «точнее» работают так же', () => {
    expect(fix('Отправь в среду, простите, в четверг.').text).toBe('Отправь в четверг.');
    expect(fix('Сумма 400, точнее 450 рублей.').text).toBe('Сумма 450 рублей.');
  });

  it('две поправки в одной фразе убираются обе', () => {
    const res = fix('Задача 4, то есть задача 5, срок пятница, то есть понедельник.');
    expect(res.fixes).toBe(2);
    expect(res.text).toContain('задача 5');
    expect(res.text).toContain('понедельник');
    expect(res.text).not.toContain('задача 4');
  });
});

describe('оговорки: уточнение — не поправка, его нельзя выкидывать', () => {
  it('«сократи, то есть убери воду» остаётся целиком', () => {
    const text = 'Сократи, то есть убери воду и вводные слова.';
    expect(fix(text).text).toBe(text);
    expect(fix(text).fixes).toBe(0);
  });

  it('«три пункта, то есть три задачи» не теряет «пункта»', () => {
    const text = 'Три пункта, то есть три задачи по проекту.';
    expect(fix(text).text).toBe(text);
  });

  it('обычный текст без маркеров не трогается', () => {
    const text = 'Привет, как дела? Я в порядке, спасибо.';
    expect(fix(text).text).toBe(text);
    expect(fix(text).fixes).toBe(0);
  });

  it('пустой текст и null не ломают ничего', () => {
    expect(fix('').text).toBe('');
    expect(fix('').fixes).toBe(0);
    expect(fix(null).text).toBe('');
  });

  it('маркер в конце фразы без замены не режет текст', () => {
    const text = 'Он пришёл, то есть';
    expect(fix(text).text).toBe(text);
  });
});

describe('оговорки: повтор слова и границы', () => {
  it('заикание убирается', () => {
    expect(dropStutter('в три в три часа')).toBe('в три часа');
  });

  it('не убирает повторы, которые человек мог сказать намеренно', () => {
    for (const text of [
      'Алло, алло, приветики.',
      'Здорово! B2B проект для 100% 100% заработка.',
      'Очень очень хорошо.',
      'Отправь отчёт завтра завтра.',
    ]) {
      expect(fix(text)).toEqual({ text, fixes: 0 });
    }
  });

  it('длинный хвост перед поправкой не отрезается целиком', () => {
    // защита: не больше шести слов, иначе можно потерять половину мысли
    const span = correctionSpan(
      'мы договорились что встреча будет в четыре',
      'в три часа',
    );
    expect(span).toBeLessThanOrEqual(6);
  });

  it('span считается по совпадающим словам с конца', () => {
    expect(correctionSpan('Звонок в 4', 'в 3 часа')).toBe(2);
    expect(correctionSpan('Позвони Пете', 'Васе')).toBe(1);
    expect(correctionSpan('Сократи', 'убери воду')).toBe(0);
  });
});
