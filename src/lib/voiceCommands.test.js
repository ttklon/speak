import { describe, expect, it } from 'vitest';
import { applyVoiceCommands, commandsFor, VOICE_COMMAND_TIP } from './voiceCommands.js';

const ru = (text) => applyVoiceCommands(text, { language: 'ru' });

describe('голосовые знаки препинания', () => {
  it('запятая внутри фразы становится запятой', () => {
    expect(ru('привет запятая как дела')).toBe('Привет, как дела.');
  });

  it('запятая, которую движок уже поставил, не удваивается', () => {
    expect(ru('привет, запятая, как дела')).toBe('Привет, как дела.');
  });

  it('точка в конце фразы закрывает предложение', () => {
    expect(ru('надо встретиться точка')).toBe('Надо встретиться.');
  });

  it('точка посреди фразы начинает новое предложение с заглавной', () => {
    expect(ru('это тест точка это точно')).toBe('Это тест. Это точно.');
  });

  it('«точка зрения» остаётся словами', () => {
    expect(ru('моя точка зрения важна')).toBe('Моя точка зрения важна.');
  });

  it('прилагательное перед «точкой» — это существительное, а не знак', () => {
    expect(ru('финальная точка проекта')).toBe('Финальная точка проекта.');
    expect(ru('болевая точка бизнеса')).toBe('Болевая точка бизнеса.');
  });

  it('«не запятая» — это слово, а не знак', () => {
    expect(ru('это не запятая тут она не нужна')).toBe('Это не запятая тут она не нужна.');
  });

  it('«точка входа» и «до этой точки» не превращаются в знаки', () => {
    expect(ru('точка входа справа')).toBe('Точка входа справа.');
    expect(ru('дойти до этой точки')).toBe('Дойти до этой точки.');
  });

  it('точка с запятой — это точка с запятой, а не две команды', () => {
    expect(ru('первое точка с запятой второе')).toBe('Первое; второе.');
  });

  it('двоеточие и тире', () => {
    expect(ru('смотри двоеточие важно')).toBe('Смотри: важно.');
    expect(ru('москва тире столица')).toBe('Москва — столица.');
  });

  it('вопросительный и восклицательный знаки', () => {
    expect(ru('ты придёшь вопросительный знак')).toBe('Ты придёшь?');
    expect(ru('ура восклицательный знак')).toBe('Ура!');
  });

  it('многоточие', () => {
    expect(ru('ну не знаю многоточие')).toBe('Ну не знаю…');
  });

  it('висячая запятая в конце превращается в точку', () => {
    expect(ru('привет запятая')).toBe('Привет.');
  });

  it('дефис остаётся дефисом', () => {
    expect(ru('это сине дефис зелёный')).toBe('Это сине-зелёный.');
  });

  it('числа с точкой не разваливаются', () => {
    expect(ru('цена 3.5 доллара')).toBe('Цена 3.5 доллара.');
    expect(ru('версия 1.6.2 готова')).toBe('Версия 1.6.2 готова.');
  });
});

describe('кавычки и скобки', () => {
  it('кавычки обнимают слово без лишних пробелов', () => {
    expect(ru('он сказал открыть кавычки привет закрыть кавычки и ушёл')).toBe(
      'Он сказал «Привет» и ушёл.',
    );
  });

  it('скобки', () => {
    expect(ru('смотри открыть скобку важно закрыть скобку')).toBe('Смотри (важно).');
  });

  it('в кавычках и скобках первая буква заглавная', () => {
    expect(ru('открыть кавычки здравствуйте закрыть кавычки сказал он')).toBe(
      '«Здравствуйте» сказал он.',
    );
  });
});

describe('переносы строк', () => {
  it('«с новой строки» делит диктовку на строки', () => {
    expect(ru('надо встретиться точка с новой строки купить хлеб')).toBe(
      'Надо встретиться.\nКупить хлеб.',
    );
  });

  it('«новый абзац» оставляет пустую строку', () => {
    expect(ru('список новый абзац первый новый абзац второй')).toBe(
      'Список.\n\nПервый.\n\nВторой.',
    );
  });

  it('перенос в начале текста не оставляет пустую строку', () => {
    expect(ru('с новой строки привет')).toBe('Привет.');
  });

  it('без команд текст остаётся одной строкой', () => {
    expect(ru('просто текст без команд')).toBe('Просто текст без команд.');
  });
});

describe('правка голосом', () => {
  it('«удалить последнее слово» убирает последнее слово', () => {
    expect(ru('купить хлеб молоко удалить последнее слово')).toBe('Купить хлеб.');
  });

  it('вместе с последним словом не удаляется соседний союз', () => {
    expect(ru('купить хлеб и молоко удали последнее слово')).toBe('Купить хлеб и.');
  });

  it('«удалить последнее предложение» убирает фразу целиком', () => {
    expect(ru('первое предложение точка второе предложение удалить последнее предложение')).toBe(
      'Первое предложение.',
    );
  });

  it('удалять нечего — текст не ломается', () => {
    expect(ru('удалить последнее слово')).toBe('');
  });

  it('«с большой буквы» поднимает следующее слово', () => {
    expect(ru('меня зовут иван с большой буквы')).toBe('Меня зовут Иван.');
    expect(ru('с большой буквы иван')).toBe('Иван.');
  });
});

describe('язык и границы', () => {
  it('английские команды работают только в английской диктовке', () => {
    expect(applyVoiceCommands('hello comma world period', { language: 'en-US' })).toBe(
      'Hello, world.',
    );
    expect(applyVoiceCommands('hello comma world', { language: 'ru' })).toBe('Hello comma world.');
  });

  it('английский «period» не трогает русский текст', () => {
    expect(applyVoiceCommands('срок period', { language: 'ru' })).toBe('Срок period.');
  });

  it('текст с уже расставленными знаками не портится', () => {
    expect(ru('Привет, как дела? Хорошо!')).toBe('Привет, как дела? Хорошо!');
  });

  it('без команд не разрывает адреса, пути, код и исходные переносы', () => {
    expect(ru('Сайт example.com открыт.')).toBe('Сайт example.com открыт.');
    expect(ru('JSON.parse(value)')).toBe('JSON.parse(value).');
    expect(ru('путь /home/user\n\nследующая строка')).toBe('Путь /home/user.\n\nСледующая строка.');
    expect(ru('Цена 1,5 рубля.')).toBe('Цена 1,5 рубля.');
  });

  it('сохраняет технические фрагменты рядом с голосовыми командами', () => {
    for (const [source, expected] of [
      ['Сайт example.com запятая работает', 'Сайт example.com, работает.'],
      ['Используй JSON.parse(value) запятая затем продолжай', 'Используй JSON.parse(value), затем продолжай.'],
      ['Ссылка https://example.com/a?x=1 запятая открыта', 'Ссылка https://example.com/a?x=1, открыта.'],
      ['Путь /home/user/file.txt точка дальше', 'Путь /home/user/file.txt. Дальше.'],
      ['Адрес hello@example.com запятая дальше', 'Адрес hello@example.com, дальше.'],
      ['Текст zsprotectedfragment0z example.com запятая дальше', 'Текст zsprotectedfragment0z example.com, дальше.'],
      ['Ссылка https://example.com/точка запятая дальше', 'Ссылка https://example.com/точка, дальше.'],
    ]) expect(ru(source)).toBe(expected);
  });

  it('сохраняет исходные переносы, если встретилась команда', () => {
    expect(ru('Первая строка запятая готово\n\nвторая строка')).toBe('Первая строка, готово.\n\nВторая строка.');
    expect(ru('текст удалить последнее\nслово')).toBe('Текст удалить последнее.\nСлово.');
  });

  it('для кода без команд не добавляет пунктуацию и не меняет регистр или отступы', () => {
    const code = '    const UserService = JSON.parse(value);\n    return UserService';
    expect(applyVoiceCommands(code, { language: 'ru', preserveFormatting: true })).toBe(code);
    expect(applyVoiceCommands('привет запятая мир', { language: 'ru', preserveFormatting: true })).toBe('Привет, мир.');
  });

  it('пустой текст и пробелы', () => {
    expect(ru('')).toBe('');
    expect(ru('   ')).toBe('');
  });

  it('пробелы не удваиваются и не остаются перед запятой', () => {
    expect(ru('привет    запятая    мир')).toBe('Привет, мир.');
  });

  it('список команд не пустой и содержит правила для интерфейса', () => {
    expect(commandsFor('ru').length).toBeGreaterThan(30);
    expect(commandsFor('en').length).toBeGreaterThan(commandsFor('ru').length);
    expect(VOICE_COMMAND_TIP).toMatch(/с новой строки/);
  });
});

describe('безопасные границы голосового удаления', () => {
  it('удаляет завершённое предложение, но оставляет предыдущее и его знак', () => {
    expect(ru('Первое предложение. Второе предложение. удалить последнее предложение')).toBe('Первое предложение.');
    expect(ru('Первое. Второе? удалить последнее предложение')).toBe('Первое.');
    expect(ru('Готово! удалить последнее предложение')).toBe('');
    expect(ru('Первое. Второе удалить последнее предложение')).toBe('Первое.');
  });
  it('не считает десятичные числа и версии границей предложения', () => {
    expect(ru('Курс 3.5 удалить последнее предложение')).toBe('');
    expect(ru('Начало. Версия 1.2.3 готова удалить последнее предложение')).toBe('Начало.');
    expect(ru('Курс 3.5 удалить последнее слово')).toBe('Курс.');
  });
  it('не удаляет лишние союзы или отрицание при удалении одного слова', () => {
    expect(ru('Привет не готов удалить последнее слово')).toBe('Привет не.');
    expect(ru('купить хлеб и молоко удалить последнее слово')).toBe('Купить хлеб и.');
  });
  it('не выполняет команды удаления с непосредственным отрицанием', () => {
    expect(ru('Доброе утро не удалить последнее слово')).toBe('Доброе утро не удалить последнее слово.');
    expect(ru('Сделай это не удалить последнее предложение')).toBe('Сделай это не удалить последнее предложение.');
  });
  it('не исполняет буквальные команды внутри имеющихся кавычек', () => {
    expect(ru('Скажи «удалить последнее слово» вслух')).toBe('Скажи «удалить последнее слово» вслух.');
    expect(ru('Скажи "удалить последнее предложение" запятая затем продолжай')).toBe('Скажи "удалить последнее предложение", затем продолжай.');
    expect(ru('Скажи «удалить последнее слово')).toBe('Скажи «удалить последнее слово.');
  });
  it('не удаляет всю цитату командой для одного слова', () => {
    expect(ru('Скажи «один два» удалить последнее слово')).toBe('Скажи «один два» удалить последнее слово.');
  });
  it('не удаляет предыдущую строку, когда в текущей нет конца предложения', () => {
    expect(ru('Первый пункт\nВторой пункт удалить последнее предложение')).toBe('Первый пункт.');
  });
});

describe('голосовое удаление: дополнительные неоднозначные случаи', () => {
  it('не удаляет целую цитату с несколькими предложениями', () => {
    expect(ru('Скажи «Первое. Второе.» удалить последнее предложение')).toBe('Скажи «Первое. Второе.» удалить последнее предложение.');
  });
  it('не удаляет при непосредственном английском отрицании', () => {
    expect(applyVoiceCommands('please do not delete last word', { language: 'en' })).toBe('Please do not delete last word.');
    expect(applyVoiceCommands("please don't delete last sentence", { language: 'en' })).toBe("Please don't delete last sentence.");
  });
  it('различает команды и защищённые цитаты при соседних знаках и других командах', () => {
    expect(ru('текст «удалить последнее слово» запятая конец')).toBe('Текст «удалить последнее слово», конец.');
    expect(ru('zsquotedfragment0z "новый абзац" запятая конец')).toBe('Zsquotedfragment0z "новый абзац", конец.');
    expect(ru('открыть кавычки привет запятая мир закрыть кавычки')).toBe('«Привет, мир».');
  });
});

describe('голосовое удаление: неоднозначная точка', () => {
  it('не считает инициалы однозначной границей и оставляет команду как текст', () => {
    expect(ru('Предыдущее. Доклад И. И. Иванова удалить последнее предложение')).toBe('Предыдущее. Доклад И. И. Иванова удалить последнее предложение.');
  });
});

describe('голосовое удаление: Unicode', () => {
  it('удаляет целый эмодзи, а не часть суррогатной пары или ZWJ-последовательности', () => {
    expect(ru('Привет 👩‍💻 удалить последнее слово')).toBe('Привет.');
    expect(ru('Флаг 🇱🇻 удалить последнее слово')).toBe('Флаг.');
    expect(ru('Привет 👍🏽 удалить последнее слово')).toBe('Привет.');
    expect(ru('Счёт 1️⃣ удалить последнее слово')).toBe('Счёт.');
  });
  it('не оставляет отдельно комбинируемые диакритики', () => {
    expect(ru('Привет cafe\u0301 удалить последнее слово')).toBe('Привет.');
  });
});

describe('голосовое удаление: не подменять тип действия', () => {
  it('не считает фразу одним словом и строку одним предложением', () => {
    expect(ru('первое второе удалить последнюю фразу')).toBe('Первое второе удалить последнюю фразу.');
    expect(ru('первое. второе удалить последнюю строку')).toBe('Первое. второе удалить последнюю строку.');
    expect(ru('первое. второе удалить последнюю строчку')).toBe('Первое. второе удалить последнюю строчку.');
  });
});
