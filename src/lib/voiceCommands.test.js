import { describe, expect, it } from 'vitest';
import { applyVoiceCommands, commandsFor, VOICE_COMMAND_TIP } from './voiceCommands.js';

const ru = (text) => applyVoiceCommands(text, { language: 'ru' });

describe('голосовые знаки препинания', () => {
  it('запятая внутри фразы становится запятой', () => {
    expect(ru('привет запятая как дела')).toBe('Привет, как дела.');
  });

  it('запятая, которую движок уже поставил, не удваивается', () => {
    expect(ru('привет, запятая, как дела')).toBe('Привет, как дела.');
  });

  it('точка в конце фразы закрывает предложение', () => {
    expect(ru('надо встретиться точка')).toBe('Надо встретиться.');
  });

  it('точка посреди фразы начинает новое предложение с заглавной', () => {
    expect(ru('это тест точка это точно')).toBe('Это тест. Это точно.');
  });

  it('«точка зрения» остаётся словами', () => {
    expect(ru('моя точка зрения важна')).toBe('Моя точка зрения важна.');
  });

  it('прилагательное перед «точкой» — это существительное, а не знак', () => {
    expect(ru('финальная точка проекта')).toBe('Финальная точка проекта.');
    expect(ru('болевая точка бизнеса')).toBe('Болевая точка бизнеса.');
  });

  it('«не запятая» — это слово, а не знак', () => {
    expect(ru('это не запятая тут она не нужна')).toBe('Это не запятая тут она не нужна.');
  });

  it('«точка входа» и «до этой точки» не превращаются в знаки', () => {
    expect(ru('точка входа справа')).toBe('Точка входа справа.');
    expect(ru('дойти до этой точки')).toBe('Дойти до этой точки.');
  });

  it('точка с запятой — это точка с запятой, а не две команды', () => {
    expect(ru('первое точка с запятой второе')).toBe('Первое; второе.');
  });

  it('двоеточие и тире', () => {
    expect(ru('смотри двоеточие важно')).toBe('Смотри: важно.');
    expect(ru('москва тире столица')).toBe('Москва — столица.');
  });

  it('вопросительный и восклицательный знаки', () => {
    expect(ru('ты придёшь вопросительный знак')).toBe('Ты придёшь?');
    expect(ru('ура восклицательный знак')).toBe('Ура!');
  });

  it('многоточие', () => {
    expect(ru('ну не знаю многоточие')).toBe('Ну не знаю…');
  });

  it('висячая запятая в конце превращается в точку', () => {
    expect(ru('привет запятая')).toBe('Привет.');
  });

  it('дефис остаётся дефисом', () => {
    expect(ru('это сине дефис зелёный')).toBe('Это сине-зелёный.');
  });

  it('числа с точкой не разваливаются', () => {
    expect(ru('цена 3.5 доллара')).toBe('Цена 3.5 доллара.');
    expect(ru('версия 1.6.2 готова')).toBe('Версия 1.6.2 готова.');
  });
});

describe('кавычки и скобки', () => {
  it('кавычки обнимают слово без лишних пробелов', () => {
    expect(ru('он сказал открыть кавычки привет закрыть кавычки и ушёл')).toBe(
      'Он сказал «Привет» и ушёл.',
    );
  });

  it('скобки', () => {
    expect(ru('смотри открыть скобку важно закрыть скобку')).toBe('Смотри (важно).');
  });

  it('в кавычках и скобках первая буква заглавная', () => {
    expect(ru('открыть кавычки здравствуйте закрыть кавычки сказал он')).toBe(
      '«Здравствуйте» сказал он.',
    );
  });
});

describe('переносы строк', () => {
  it('«с новой строки» делит диктовку на строки', () => {
    expect(ru('надо встретиться точка с новой строки купить хлеб')).toBe(
      'Надо встретиться.\nКупить хлеб.',
    );
  });

  it('«новый абзац» оставляет пустую строку', () => {
    expect(ru('список новый абзац первый новый абзац второй')).toBe(
      'Список.\n\nПервый.\n\nВторой.',
    );
  });

  it('перенос в начале текста не оставляет пустую строку', () => {
    expect(ru('с новой строки привет')).toBe('Привет.');
  });

  it('без команд текст остаётся одной строкой', () => {
    expect(ru('просто текст без команд')).toBe('Просто текст без команд.');
  });
});

describe('правка голосом', () => {
  it('«удалить последнее слово» убирает последнее слово', () => {
    expect(ru('купить хлеб молоко удалить последнее слово')).toBe('Купить хлеб.');
  });

  it('вместе с последним словом уходит предлог, который остался висеть', () => {
    expect(ru('купить хлеб и молоко удали последнее слово')).toBe('Купить хлеб.');
  });

  it('«удалить последнее предложение» убирает фразу целиком', () => {
    expect(ru('первое предложение точка второе предложение удалить последнее предложение')).toBe(
      'Первое предложение.',
    );
  });

  it('удалять нечего — текст не ломается', () => {
    expect(ru('удалить последнее слово')).toBe('');
  });

  it('«с большой буквы» поднимает следующее слово', () => {
    expect(ru('меня зовут иван с большой буквы')).toBe('Меня зовут Иван.');
    expect(ru('с большой буквы иван')).toBe('Иван.');
  });
});

describe('язык и границы', () => {
  it('английские команды работают только в английской диктовке', () => {
    expect(applyVoiceCommands('hello comma world period', { language: 'en-US' })).toBe(
      'Hello, world.',
    );
    expect(applyVoiceCommands('hello comma world', { language: 'ru' })).toBe('Hello comma world.');
  });

  it('английский «period» не трогает русский текст', () => {
    expect(applyVoiceCommands('срок period', { language: 'ru' })).toBe('Срок period.');
  });

  it('текст с уже расставленными знаками не портится', () => {
    expect(ru('Привет, как дела? Хорошо!')).toBe('Привет, как дела? Хорошо!');
  });

  it('пустой текст и пробелы', () => {
    expect(ru('')).toBe('');
    expect(ru('   ')).toBe('');
  });

  it('пробелы не удваиваются и не остаются перед запятой', () => {
    expect(ru('привет    запятая    мир')).toBe('Привет, мир.');
  });

  it('список команд не пустой и содержит правила для интерфейса', () => {
    expect(commandsFor('ru').length).toBeGreaterThan(30);
    expect(commandsFor('en').length).toBeGreaterThan(commandsFor('ru').length);
    expect(VOICE_COMMAND_TIP).toMatch(/с новой строки/);
  });
});
