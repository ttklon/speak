/**
 * Текст живой расшифровки для черновика и плашки.
 *
 * whisper не потоковый: пока человек говорит, приложение раз в пару секунд
 * распознаёт накопленный звук. Чтобы запросы укладывались во время ответа,
 * окно ограничено (по умолчанию 30 с). Когда запись длиннее окна, распознан
 * только хвост — и показать его как «весь текст» было бы обманом. Поэтому
 * начало честно помечается многоточием: человек видит, что раньше были слова,
 * которые сейчас не пересчитаны (итоговый текст в конце всё равно полный).
 */
export function formatLiveDraft({ text = '', truncated = false } = {}) {
  const clean = String(text || '').replace(/\s+/g, ' ').trim();
  if (!clean) return '';
  if (!truncated) return clean;
  // не дублируем многоточие, если движок сам начал с него
  return clean.startsWith('…') ? clean : `… ${clean}`;
}

export default formatLiveDraft;
