/**
 * Что приложение имеет право делать с распознанным текстом.
 *
 * Зачем отдельная функция: правки текста раньше были размазаны по конвейеру
 * диктовки (чистка, оговорки, оформление под окно, переписывание моделью), и
 * «не трогать мой текст» пришлось бы собирать из четырёх условий в четырёх
 * местах. Одно место — один ответ на вопрос «что будет с моим текстом», и его
 * можно проверить тестом, не поднимая микрофон.
 *
 * Что остаётся при любом раскладе: словарь (человек сам его завёл), голосовые
 * команды («запятая», «с новой строки») и быстрые блоки («моя подпись»). Это
 * прямые указания человека, а не догадки приложения о том, как лучше.
 */
export function textPolicy(settings = {}) {
  const preserve = settings.preserveText === true;
  // Общий тумблер обработки; очистка обычной диктовки не принимает
  // результат, который удалил исходные слова или знаки.
  const polishing = !preserve && settings.aiProcessing !== false;
  return {
    /** Приложение не меняет текст вообще (кроме словаря и команд). */
    preserve,
    /** Применять осторожную построчную очистку обычной диктовки. */
    clean: polishing,
    /** Убирать оговорки: «в четыре… то есть в три» → «в три». */
    fixSelfCorrections: !preserve,
    /** Подгонять знаки и заглавную под окно вставки. */
    formatForApp: !preserve,
    /** Отдавать текст локальной модели на переписывание. */
    // по умолчанию полировка включена: выключает её только явное «нет»
    rewriteWithModel: polishing && settings.aiDictationRewrite !== false,
    keepDictionary: true,
    keepVoiceCommands: true,
    keepSnippets: true,
  };
}
