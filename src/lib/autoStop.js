/**
 * Авто-стоп по тишине.
 *
 * Зачем: в режиме «переключатель» (нажал — говоришь — нажал) человек часто
 * уходит, не выключив запись: приходит письмо, звонок, разговор. Тогда минуты
 * тишины летят в распознавание, а потом в историю попадает пустая запись.
 * В режиме удержания клавиши это невозможно — там стоп даёт сама клавиша.
 *
 * У всех разобранных аналогов (whisper-type, Handy, Гига Писарь) эта защита
 * есть: 15–20 секунд тишины — запись завершается. Мы сознательно считаем тишину
 * и от старта записи: если человек нажал хоткей и не сказал ничего, ждать
 * девяносто секунд сторожа бессмысленно.
 *
 * Модуль намеренно без побочных эффектов: время передаётся аргументом, поэтому
 * поведение проверяется тестом за микросекунды, без ожидания двадцати секунд.
 */

/** Сколько тишины подряд считать концом диктовки. */
export const AUTO_STOP_IDLE_MS = 20000;

/**
 * Порог «тихо/громко» по шкале уровня микрофона (0…1, после сглаживания).
 * Уровень у нас — пик огибающей после нормализации, речь на обычном микрофоне
 * уверенно даёт больше 0,05; 0,03 отделяет шум комнаты от шёпота.
 */
export const AUTO_STOP_LEVEL = 0.03;

/**
 * Создать сторож тишины.
 *
 * @param {object} [opts]
 * @param {number} [opts.idleMs] сколько тишины подряд считается концом речи
 * @param {number} [opts.threshold] уровень, ниже которого считаем тишиной
 * @param {number} [opts.now] текущее время старта, мс
 */
export function createSilenceWatch({ idleMs = AUTO_STOP_IDLE_MS, threshold = AUTO_STOP_LEVEL, now = 0 } = {}) {
  let lastLoud = Number(now) || 0;
  return {
    /**
     * Скормить очередной замер уровня.
     * @returns {boolean} пора останавливать запись
     */
    feed(level, at) {
      const t = Number(at);
      if (!Number.isFinite(t)) return false;
      if ((Number(level) || 0) >= threshold) {
        lastLoud = t;
        return false;
      }
      return t - lastLoud >= idleMs;
    },
    /** Сколько миллисекунд подряд тихо на момент `at`. */
    silentFor(at) {
      return Math.max(0, (Number(at) || 0) - lastLoud);
    },
    /** Сбросить отсчёт (например, после снятия с паузы). */
    reset(at = 0) {
      lastLoud = Number(at) || 0;
    },
  };
}

/**
 * Текст сообщения, чтобы остановка не выглядела поломкой.
 * «Запись остановилась сама» — это ровно то, что человек должен прочитать.
 */
export function autoStopNotice(idleMs = AUTO_STOP_IDLE_MS) {
  const seconds = Math.max(1, Math.round((Number(idleMs) || AUTO_STOP_IDLE_MS) / 1000));
  return `Запись остановлена сама: ${seconds} секунд тишины. Сказанное уже расшифровано.`;
}
