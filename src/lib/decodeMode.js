/**
 * Режим «скорость против точности» — словами и с честным объяснением.
 *
 * Зачем отдельный файл: приложение уже подстраивается под машину по замерам
 * (electron/adaptiveDecode.cjs), но человек не мог ни увидеть это решение, ни
 * повлиять на него. «Почему сегодня медленно?», «почему пропало слово?» —
 * вопросы, на которые нужен ответ в интерфейсе, а не в голове разработчика.
 *
 * Три режима:
 *  - «Авто» — решает замер: успевает движок или нет (по умолчанию);
 *  - «Быстро» — только быстрый проход, второй — лишь если текста нет совсем;
 *  - «Точно» — честный проход всегда: широкий перебор, полное окно, перебор
 *    температур. Дороже по времени, зато одинаково на любой машине.
 */

export const DECODE_MODES = [
  {
    id: 'auto',
    label: 'Авто',
    hint: 'По замерам: если движок успевает — считаем честно сразу, если нет — быстро.',
  },
  {
    id: 'fast',
    label: 'Быстро',
    hint: 'Только быстрый проход. Второй — лишь когда текста не получилось совсем.',
  },
  {
    id: 'accurate',
    label: 'Точно',
    hint: 'Честный проход всегда: шире перебор вариантов, полное окно, перебор температур.',
  },
];

export const DEFAULT_DECODE_MODE = 'auto';

/** Из сохранённого значения — известный режим (чужое не ломает поведение). */
export function normalizeDecodeMode(value) {
  const id = String(value || '').trim().toLowerCase();
  return DECODE_MODES.some((m) => m.id === id) ? id : DEFAULT_DECODE_MODE;
}

export function decodeModeLabel(value) {
  const id = normalizeDecodeMode(value);
  return DECODE_MODES.find((m) => m.id === id)?.label || 'Авто';
}

/**
 * Строка «что было на этой машине»: коэффициент и что из него следует.
 * Никаких процентов «скорости» — только отношение времени счёта к длительности
 * речи, которое можно проверить самому.
 */
export function describeMeasured({ factor = null, samples = 0, mode = 'auto', thorough = false } = {}) {
  const id = normalizeDecodeMode(mode);
  if (id === 'accurate') {
    return 'Режим «Точно»: честный проход всегда, независимо от замеров.';
  }
  if (id === 'fast') {
    return 'Режим «Быстро»: только быстрый проход, замеры не ускоряют и не замедляют.';
  }
  if (factor === null || factor === undefined || !samples) {
    return 'Замеров пока нет: первая диктовка пойдёт быстрым проходом, дальше приложение решит само.';
  }
  const percent = Math.round(factor * 100);
  const base = `На этой машине счёт занимает ${percent} % от длительности речи (по ${samples} ${plural(samples, 'проходу', 'проходам', 'проходам')}).`;
  if (thorough) return `${base} Движок успевает — считаем честно с первого раза.`;
  if (factor > 1.25) {
    return `${base} Движку тяжело: быстрый проход, а если текст подозрительный — второй.`;
  }
  return `${base} Запас небольшой: быстрый проход, второй — по нужде.`;
}

function plural(n, one, few, many) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
