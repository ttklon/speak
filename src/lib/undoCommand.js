/**
 * Распознавание голосовой команды «отмени». Автоматическое стирание в чужом
 * окне приостановлено, пока нельзя подтвердить положение курсора и содержимое.
 */

/** Что человек говорит, когда хочет убрать последнюю вставку. */
export const UNDO_PHRASES = [
  'отмени',
  'отмена',
  'отмени вставку',
  'отмени последнее',
  'отмени последнюю вставку',
  'отмени текст',
  'отмени это',
  'убери это',
  'убери вставку',
  'убери последнее',
  'убери последнюю вставку',
  'удали последнее',
  'удали последнюю вставку',
  'стереть последнее',
  'верни как было',
];

const PHRASES = new Set(UNDO_PHRASES);

/**
 * Приведение к сравнимому виду: регистр, знаки, лишние пробелы.
 * Знаки выкидываем потому, что движок ставит «Отмени.» с точкой, а человек
 * этого не говорил.
 */
export function normalizeUndoPhrase(text = '') {
  return String(text)
    .toLowerCase()
    .replace(/[.,!?;:…«»"'`()\-—–]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Это команда «убрать последнюю вставку»? */
export function isUndoCommand(text = '') {
  // Распознанная цитата — буквальный текст, даже если в ней одна команда.
  if (/[«»“”"]/u.test(String(text ?? ''))) return false;
  const value = normalizeUndoPhrase(text);
  return Boolean(value) && PHRASES.has(value);
}

/**
 * Что показать человеку, когда убирать нечего.
 * Причина приходит из main-процесса, но говорит она на языке движка
 * («ttl-expired»), а человеку нужно предложение.
 */
export function undoFailureText(reason = '') {
  const value = String(reason || '').toLowerCase();
  if (!value) return 'Последнюю вставку уже не убрать — но текст остался в истории.';
  if (value === 'неподтверждённая позиция курсора') {
    return 'Не могу проверить положение курсора, поэтому не стираю текст. Проверьте нужное приложение и отмените или исправьте вручную; текст диктовки остался в истории.';
  }
  if (/минут|ttl|давно|устар/.test(value)) {
    return 'Прошло больше двух минут — так я не рискую стереть ваши слова. Текст остался в истории.';
  }
  if (/окно|друг|window|сейчас|был в/.test(value)) {
    return 'Активное окно уже другое: стирать наугад не буду. Текст остался в истории.';
  }
  if (/нечего|пусто|nothing/.test(value)) {
    return 'Убирать нечего: до этого я ничего не вставлял.';
  }
  if (/windows|только/.test(value)) {
    return 'Убрать вставку можно только в приложении для Windows: в браузере я не вижу чужих окон.';
  }
  if (/помощник|собрать|compiler|sendinput/.test(value)) {
    return 'Не смог отправить стирание в активное окно. Текст остался в истории — удалите руками.';
  }
  return `${reason} Текст остался в истории.`;
}
